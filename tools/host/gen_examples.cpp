// gen_examples.cpp - writes example capture logs using the REAL
// IRremoteESP8266 encoders (host build, see tools/host_check.sh).
//
// The output uses the same text format as src/capture.cpp prints, so
// tools/analyse_ir.py can read it. These are NOT recordings of a real unit;
// they are what the library would transmit for the stated settings.
#include <stdio.h>

#include <string>

#include "IRsend_test.h"
#include "ir_Mitsubishi.h"
#include "ir_MitsubishiHeavy.h"

static int g_n = 0;

static void dump(IRsendTest &tx, const char *label, const char *proto,
                 const uint8_t *state, uint16_t nbytes) {
  uint16_t last = tx.last;
  if (last & 1) last--;  // a receiver never sees the trailing gap: drop it
  g_n++;
  printf("# label: %s\n", label);
  printf("=== #%d t=%dms\n", g_n, g_n * 4000);
  printf("PROTO %s bits=%u overflow=NO\n", proto, nbytes * 8);
  printf("STATE ");
  for (uint16_t i = 0; i < nbytes; i++) printf("%02X", state[i]);
  printf("\nRAW,%u", last + 1);
  for (uint16_t i = 0; i <= last; i++) printf(",%u", (unsigned)tx.output[i]);
  printf("\n");
  tx.reset();
}

static void mitsubishiElectric() {
  printf("## Generated by tools/host/gen_examples.cpp using the IRremoteESP8266\n");
  printf("## MITSUBISHI_AC encoder. NOT captured from a real unit.\n");
  IRsendTest tx(0);
  IRMitsubishiAC ac(0);
  ac.begin();
  ac.on();
  ac.setMode(kMitsubishiAcCool);
  ac.setTemp(22);
  ac.setFan(kMitsubishiAcFanAuto);
  ac.setVane(kMitsubishiAcVaneAuto);
  auto send = [&](const char *label) {
    tx.reset();
    uint8_t *raw = ac.getRaw();
    tx.sendMitsubishiAC(raw, kMitsubishiACStateLength, kMitsubishiACMinRepeat);
    dump(tx, label, "MITSUBISHI_AC", raw, kMitsubishiACStateLength);
  };
  send("cool 22C fan auto vane auto (base)");
  ac.setTemp(23);
  send("temp 23C");
  ac.setTemp(23.5);
  send("temp 23.5C");
  ac.setTemp(22);
  ac.setFan(3);
  send("fan speed 3");
  ac.setFan(kMitsubishiAcFanAuto);
  ac.setVane(kMitsubishiAcVaneHighest);
  send("vane highest");
  ac.setVane(kMitsubishiAcVaneAuto);
  ac.setMode(kMitsubishiAcHeat);
  send("mode heat");
  ac.setMode(kMitsubishiAcDry);
  send("mode dry");
  ac.setMode(kMitsubishiAcCool);
  ac.off();
  send("power off");
}

static void mitsubishiHeavy152() {
  printf("## Generated by tools/host/gen_examples.cpp using the IRremoteESP8266\n");
  printf("## MITSUBISHI_HEAVY_152 encoder. NOT captured from a real unit.\n");
  g_n = 0;
  IRsendTest tx(0);
  IRMitsubishiHeavy152Ac ac(0);
  ac.begin();
  ac.on();
  ac.setMode(kMitsubishiHeavyCool);
  ac.setTemp(22);
  ac.setFan(kMitsubishiHeavy152FanAuto);
  auto send = [&](const char *label) {
    tx.reset();
    uint8_t *raw = ac.getRaw();
    tx.sendMitsubishiHeavy152(raw, kMitsubishiHeavy152StateLength,
                              kMitsubishiHeavy152MinRepeat);
    dump(tx, label, "MITSUBISHI_HEAVY_152", raw, kMitsubishiHeavy152StateLength);
  };
  send("cool 22C fan auto (base)");
  ac.setTemp(23);
  send("temp 23C");
  ac.setTemp(22);
  ac.setFan(kMitsubishiHeavy152FanHigh);
  send("fan high");
  ac.setFan(kMitsubishiHeavy152FanAuto);
  ac.off();
  send("power off");
}

int main(int argc, char **argv) {
  const std::string which = argc > 1 ? argv[1] : "electric";
  if (which == "heavy") mitsubishiHeavy152();
  else mitsubishiElectric();
  return 0;
}
